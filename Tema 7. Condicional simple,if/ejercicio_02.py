# Ejercicio 02: Saldo mínimo
# Enunciado: Solicitar un saldo. Si es igual o superior a 50000, indicar que cumple el saldo mínimo.
# Entrada: Saldo
# Proceso: if saldo >= 50000
# Salida: Mensaje de cumplimiento

saldo = float(input("Ingrese el saldo: "))
if saldo >= 50000:
    print("Cumple el saldo mínimo requerido")

# Ejercicio 04: Entrega a tiempo
# Enunciado: Solicitar cuántos días faltan para la fecha límite. Si es mayor que cero, indicar que todavía hay tiempo.
# Entrada: Días restantes
# Proceso: if dias > 0
# Salida: Mensaje de que hay tiempo

dias = int(input("¿Cuántos días faltan para la fecha límite? "))
if dias > 0:
    print("Todavía hay tiempo para entregar")

# Ejercicio 01: Promedio de tres notas 
# Enunciado: Solicitar tres notas, calcular el promedio y mostrarlo.
# Entrada: nota1, nota2 y nota3
# Proceso: promedio = (nota1 + nota2 + nota3) / 3
# Salida: Promedio

nota1 = float(input("Primera nota: "))
nota2 = float(input("Segunda nota: "))
nota3 = float(input("Tercera nota: "))
promedio = (nota1 + nota2 + nota3) / 3
print("Promedio:", promedio)
#Ejercicio 3. Básico — Costo de dos productos
#Enunciado:Solicite el precio de dos productos y calcule el valor total de la compra.
#Entrada:precio de dos productos (primer_producto,segundo_producto)
#proceso: total = primer_producto + segundo_producto

# Ejercicio 03: Mayor o menor de edad
# Enunciado: Solicitar la edad y mostrar un mensaje según sea mayor o menor de edad.
# Entrada: Edad
# Proceso: if edad >= 18 / else
# Salida: Mayor o menor de edad

edad = int(input("Ingrese la edad: "))
if edad >= 18:
    print("Es mayor de edad")
else:
    print("Es menor de edad")

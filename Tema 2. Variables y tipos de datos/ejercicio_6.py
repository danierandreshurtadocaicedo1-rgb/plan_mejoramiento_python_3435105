# Enunciado: Solicitar nombre de un equipo, cantidad de integrantes y si el proyecto está activo. Presentar los datos con tipos apropiados.
# Entrada: Nombre (str), integrantes (int), activo (str)
# Proceso:Registrar la respuesta de si el proyecto está activo

# Ejercicio 03: Información de un vehículo
# Enunciado: Solicitar marca, modelo y año de fabricación. Mostrar la información organizada.
# Entrada: Marca (str), modelo (str), año (int)
# Proceso: Almacenar cada dato en una variable
# Salida: información del vehiculo

marca = input("ingrese la Marca del vehiculo: ")
modelo = input("ingrese el Modelo del vehiculo: ")
año = int(input("ingrese el Año de fabricación del vehiculo: "))
print("--- Información del vehículo ---")
print("Marca:", marca)
print("Modelo:", modelo)
print("Año:", año)
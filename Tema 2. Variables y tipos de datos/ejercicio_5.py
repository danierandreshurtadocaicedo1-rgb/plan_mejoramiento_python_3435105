# Ejercicio 05: Registro de un proyecto
# Enunciado: Solicitar nombre de un proyecto, número de integrantes y presupuesto estimado. Mostrar los datos.
# Entrada: Nombre (str), integrantes (int), presupuesto (float)
# Proceso: Almacenar cada dato en una variable
# Salida: Datos del proyecto

proyecto = input("Nombre del proyecto: ")
integrantes = int(input("Número de integrantes: "))
presupuesto = float(input("Presupuesto estimado: "))
print("Proyecto:", proyecto)
print("Integrantes:", integrantes)
print("Presupuesto estimado:", presupuesto)
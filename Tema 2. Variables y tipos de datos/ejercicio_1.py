# Ejercicio 01: Datos de un aprendiz 
# Enunciado: Solicitar nombre, edad y promedio de un aprendiz y presentar los datos.
# Entrada: Nombre (str), edad (int), promedio (float)
# Proceso: Almacenar cada dato en una variable
# Salida: Los tres datos

nombre = input("Ingrese el nombre: ")
edad = int(input("Ingrese la edad: "))
promedio = float(input("Ingrese el promedio: "))
print("Nombre:", nombre)
print("Edad:", edad)
print("Promedio:", promedio)
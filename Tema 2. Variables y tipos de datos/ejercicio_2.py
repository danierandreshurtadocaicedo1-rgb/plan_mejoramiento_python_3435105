# Ejercicio 02: Datos de un producto
# Enunciado: Solicitar nombre, precio y cantidad disponible de un producto. Presentar los datos.
# Entrada: Nombre (str), precio (float), cantidad (int)
# Proceso: Almacenar cada dato en una variable 
# Salida: los tres datos 

nombre = input("ingrese el Nombre del producto: ")
precio = float(input("ingrese el Precio: "))
cantidad = int(input("ingrese la Cantidad disponible: "))
print("Producto:", nombre)
print("Precio:", precio)
print("Cantidad disponible:", cantidad)